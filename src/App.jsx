function getDtfUnit(m, totalQty, si) {
  const tbl = m.dtfTable || [[9,700,900,1200],[49,370,580,680],[99,270,480,580],[299,250,450,550],[9999,220,430,530]];
  const row = tbl.find(r => totalQty <= r[0]);
  return row ? row[1 + Number(si)] : 0;
}

// カッティング単価
function getCuttingUnit(m, qty, si) {
  const row = m.cuttingTable.find(r => qty <= r[0]);
  return row ? row[1 + Number(si)] : 0;
}

// ボディ掛け率（合計枚数基準）
function getBodyRate(m, totalQty) {
  const row = m.bodyRate.find(r => totalQty <= r[0]);
  return row ? row[1] : 1.4;
}

// タオル単価
function getTowelUnit(m, type, qty) {
  const t = m.towelTypes.find(x => x.id === type);
  if (!t) return 0;
  const row = t.table.find(r => qty <= r[0]);
  return row ? row[1] : 0;
}

// 送料
function calcShip(m, sub, dest) {
  const s = m.shipping[dest];
  if (!s) return 0;
  return sub >= s.threshold ? 0 : s.fee;
}

// 全品目計算
function calcAll(master, items, sharedLocations) {
  const totalQty = items.reduce((s, i) => s + (Number(i.qty) || 0), 0);
  const bodyRate = getBodyRate(master, totalQty);
  const locs = sharedLocations || [];

  // 共通印刷箇所のインク代・製版代（全品番共通）
  let inkUnitTotal = 0;
  let plateFeeTotal = 0;
  for (const loc of locs) {
    if (loc.method === "none") continue;
    if (loc.method === "screen") {
      inkUnitTotal += getInkUnit(master, totalQty, loc.colors);
      plateFeeTotal += master.plateFee[loc.plateSize] || 0;
    }
    if (loc.method === "cutting") {
      inkUnitTotal += getCuttingUnit(master, totalQty, loc.cuttingSizeIdx);
    }
    if (loc.method === "dtf") {
      inkUnitTotal += getDtfUnit(master, totalQty, loc.dtfSizeIdx || 0);
    }
  }

  return items.map(item => {
    const qty = Number(item.qty) || 0;

    // サイズUP・カラー追加料金（上代に加算してから掛け率計算）
    // ボディ単価（上代 ÷ 掛け率）※サイズUP・カラー料金は金額に含まない
    let bodyUnit = 0;
    if (item.productType === "apparel_list") {
      bodyUnit = Math.round(Number(item.listPrice) / bodyRate / 10) * 10;
    } else if (item.productType === "towel") {
      bodyUnit = getTowelUnit(master, item.towelType, qty);
    } else {
      bodyUnit = Number(item.manualUnitPrice) || 0;
    }

    // デザイン構成費（1品目のみ・2品目以降はなし）
    const itemIndex = items.indexOf(item);
    const designFee = itemIndex > 0
      ? 0
      : item.designComplexity === "complex"
      ? master.designFee.complex
      : item.designComplexity === "none"
      ? 0
      : item.designComplexity === "bring"
      ? 2000
      : master.designFee.simple;

    // 個別袋詰め料金（税込55円 → 税別50円）
    const bagUnitIn = item.bagOption ? 55 : 0;
    const bagUnitEx = item.bagOption ? Math.round(55 / (1 + TAX)) : 0;

    // 合計
    const fixedFees = plateFeeTotal + designFee;
    const unitEx = bodyUnit + inkUnitTotal + bagUnitEx + (qty > 0 ? fixedFees / qty : 0);
    const unitIn = unitEx * (1 + TAX);
    const totalEx = bodyUnit * qty + inkUnitTotal * qty + bagUnitEx * qty + fixedFees;

    return {
      id: item.id, bodyUnit, inkUnitTotal, plateFeeTotal, designFee,
      fixedFees, bagUnitEx, unitEx, unitIn, totalEx, qty, bodyRate,
    };
  });
}

